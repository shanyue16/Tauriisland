/**
 * 「这一行根本不是歌词」的判定 —— **所有本地源共用一份**。
 *
 * ## 为什么单独抽出来
 * 本机第三方程序的歌词文件里，混着大量不是内容的东西，而且**每个源的混法都不一样**：
 * - Folia（32109）：`词：许嵩` / `曲：许嵩` / `编曲：田汨`（署名）、`......`（前奏占位）、
 *   `op：风升乐起`（片头标记）、`未经著作权人…使用`（版权声明）、`男：`（对唱角色标记）
 * - Now Playing（9863）：同一类署名，外加片尾的
 *   `歌曲企划：` / `营销团队：` / `监制：` / `特别鸣谢：` / `出品：` / `出品人：`
 *
 * 这些行既不是标题卡（解析不出身份）、也不一定是零长度行，所以身份门禁与标题卡判定
 * 都不会动它们 —— 不显式过滤就会**原样当成歌词显示在岛上**。
 *
 * 抽成一份的理由很直接：**两份正则列表必然漂移**，而漂移的表现是
 * 「这个源干净了、那个源又开始漏出品人」这种极难复现的脏数据 bug。
 *
 * ## 判据的共同形状：必须有**必需的分隔符**
 * `词：` 会被拦，但 `曲终人散…` 这种真实歌词行**绝不能**被误伤 ——
 * 所以署名类一律要求**冒号**（`^词\s*[：:]`），而不是只匹配开头的「词」「曲」。
 */

import type { LyricLine } from "../../types/lyrics";

/** `......` 之类的前奏占位行 */
const PLACEHOLDER = /^[.．。…·\s]+$/;

/**
 * 署名行。
 *
 * **实测不断扩表的原因**：字段名是**开放集合**，真 payload 里出现过：
 * ```
 * 词Lyricist：郑浩              出品人 Publisher：颜陌
 * 监制Executive Producer：…     制作人Music Producer：…
 * Bass：苏虹文                  制作团队：拨片音乐
 * 推广支持：QQ音乐·银河计划       艺术指导：程楚楚(廊坊师范学院）
 * 弦乐录音：王小四               
 * ```
 * 前两版分别漏了「英文标签」和「纯英文字段」，所以现在是三合一：
 * ① 中文字段（+ 可选拉丁标签）；② **纯拉丁字段**（`Bass：` / `Producer：`）。
 *
 * 两个分支都必须**紧跟冒号**才成立，所以 `曲终人散…` / `还没习惯…` 这类真实歌词行不会误伤
 * （汉字后面不是冒号；纯英文分支要求冒号在前 21 个字符内出现）。
 */
const CREDIT =
  /^(?:(?:作词|作曲|编曲|填词|混音|母带|制作人|制作团队|制作|监制|总监制|出品人|出品|发行|录音师|录音|配唱|吉他|贝斯|鼓|键盘|和声|统筹|企划|歌曲企划|营销|营销团队|联合营销|推广支持|推广|宣发|策划|特别鸣谢|特别感谢|鸣谢|致谢|艺术指导|弦乐|弦乐编写|弦乐录音|作词人|作曲人|出版|版权|封面|视觉|设计|造型|演唱|原唱|词|曲|op|ed)\s*(?:[A-Za-z][A-Za-z.&/ ]*)?|[A-Za-z][A-Za-z.&/ ]{0,20})\s*[：:]/i;

/** 版权声明行。实测原文：`未经著作权人书面许可不得以任何方式（包括翻唱、翻录等）使用` */
const COPYRIGHT = /(著作权|版权所有|未经许可|未经授权|翻唱|翻录|侵权|必究)/;

/** 纯角色标记行（对唱标注），如 `男：` / `女：` / `合：` —— 冒号后面没有内容 */
const ROLE_ONLY = /^(男|女|合|合唱|全体)\s*[：:]\s*$/;

/**
 * 这一行是不是「根本不是歌词」的元数据/声明行。
 *
 * ⚠️ 只判**整行**语义，不判长度：真实的短歌词行（`啊` / `嘿`）必须留下。
 */
export function isNonLyricLine(text: string): boolean {
  return (
    PLACEHOLDER.test(text) || CREDIT.test(text) || COPYRIGHT.test(text) || ROLE_ONLY.test(text)
  );
}

/**
 * 过滤整份歌词：去掉声明行、空行、以及**零长度行**。
 *
 * 零长度行的实例：酷狗推广行 `『听歌就在中国酷狗*星曜计划』`（`startTime >= endTime`）。
 * 它带真实时间戳、也叫「一行歌词」，只有拿时间判才拦得住。
 */
export function stripNoise(lines: LyricLine[]): LyricLine[] {
  return lines.filter((l) => {
    if (!l.text || !l.text.trim()) return false;
    if (isNonLyricLine(l.text.trim())) return false;
    if (typeof l.end_ms === "number" && l.end_ms <= l.time_ms) return false;
    return true;
  });
}
